#!/usr/bin/env bash
# ======================================================================
#  Order Rescue Lite - per-laptop setup.
#  Generates a fun, unique SEAT name for this laptop (no hardcoded seat
#  numbers - any number of laptops), wires THIS laptop's own Dynatrace
#  tenant, verifies the token, and writes a git-ignored .env.
#
#  Flow per laptop:  sign in to AWS  ->  bash scripts/setup.sh  ->  bash scripts/deploy.sh
#  Needs: curl. (No AWS calls here - deploy.sh does those.)
# ======================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

command -v curl >/dev/null 2>&1 || { echo "ERROR: curl not found."; exit 1; }

if [ -f .env ]; then
  printf ".env already exists. Overwrite it? [y/N] "
  read -r ans; [ "$ans" = "y" ] || [ "$ans" = "Y" ] || { echo "Keeping existing .env. Nothing changed."; exit 0; }
fi

# --- generate a fun, unique seat name (adjective-animal-xxxx) ---------------
ADJECTIVES=(cosmic turbo quantum neon rogue atomic lunar solar mega hyper swift brave witty zesty groovy funky nimble clever jolly plucky)
ANIMALS=(otter narwhal llama yak gecko panda walrus falcon koala mantis badger lemur raven heron ocelot dingo tapir quokka wombat axolotl)
gen_seat() {
  local a="${ADJECTIVES[$((RANDOM % ${#ADJECTIVES[@]}))]}"
  local n="${ANIMALS[$((RANDOM % ${#ANIMALS[@]}))]}"
  printf '%s-%s-%04x' "$a" "$n" "$((RANDOM % 65536))"
}
valid_lane() { printf '%s' "$1" | grep -Eq '^[a-z0-9]([a-z0-9-]{0,38}[a-z0-9])?$'; }

echo "== Order Rescue Lite setup =="
GEN="$(gen_seat)"
printf "Seat name for this laptop [%s] (Enter to accept, or type your own): " "$GEN"
read -r LANE
LANE="${LANE:-$GEN}"
valid_lane "$LANE" || { echo "ERROR: invalid seat '$LANE' (lowercase/digits/dashes, 2-40, no leading/trailing dash)."; exit 1; }
echo "Seat: $LANE"

# --- this laptop's own Dynatrace tenant ------------------------------------
echo ""
echo "Dynatrace for THIS laptop (leave the tenant blank to skip tracing for now):"
printf "  Tenant / environment id (the part before .live.dynatrace.com, e.g. abc12345): "
read -r TENANT

OTEL_ENDPOINT=""
OTEL_HEADERS=""
if [ -n "$TENANT" ]; then
  printf "  Ingest API token (scope: openTelemetryTrace.ingest) dt0c01....: "
  read -r TOKEN
  [ -n "$TOKEN" ] || { echo "ERROR: a tenant was given but no token."; exit 1; }

  OTEL_ENDPOINT="https://${TENANT}.live.dynatrace.com/api/v2/otlp/v1/traces"
  echo "  Verifying the token against $OTEL_ENDPOINT ..."
  # Empty body -> 400 when auth is OK, 401/403 when the token is bad.
  CODE="$(curl -s -o /dev/null -w '%{http_code}' -X POST "$OTEL_ENDPOINT" \
    -H "Authorization: Api-Token ${TOKEN}" \
    -H "Content-Type: application/x-protobuf" --data-binary '' || echo 000)"
  case "$CODE" in
    401|403) echo "ERROR: Dynatrace rejected the token (HTTP $CODE). Check the token and its 'openTelemetryTrace.ingest' scope."; exit 1 ;;
    000)     echo "ERROR: could not reach $OTEL_ENDPOINT. Check the tenant id / network."; exit 1 ;;
    *)       echo "  OK (HTTP $CODE) - token accepted." ;;
  esac
  # Store URL-encoded (%20 for the space) - OTEL header values are URL-encoded.
  OTEL_HEADERS="Authorization=Api-Token%20${TOKEN}"
fi

umask 077   # .env holds a token; keep it owner-only
cat > .env <<EOF
# Generated by scripts/setup.sh - this laptop's seat + Dynatrace tenant.
# Gitignored. Never commit this file.
LANE=${LANE}

MODEL_MODE=bedrock
AWS_REGION=${AWS_REGION:-us-east-1}
AWS_EXPECTED_ACCOUNT_ID=${AWS_EXPECTED_ACCOUNT_ID:-}
BEDROCK_MODEL_ID=us.anthropic.claude-haiku-4-5-20251001-v1:0

OTEL_EXPORTER_OTLP_TRACES_ENDPOINT=${OTEL_ENDPOINT}
OTEL_EXPORTER_OTLP_TRACES_HEADERS=${OTEL_HEADERS}

ORDER_DELAY_MS=1500
EOF

echo ""
echo "Wrote .env for seat '$LANE'."
[ -n "$OTEL_ENDPOINT" ] && echo "Tracing -> $OTEL_ENDPOINT" || echo "Tracing is OFF (no tenant given)."
echo "Next: bash scripts/deploy.sh"
